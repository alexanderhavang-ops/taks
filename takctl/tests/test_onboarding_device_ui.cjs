const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const h = (type, props, ...children) => ({type, props: props || {}, children});
const ctx = {window: {h}, React: {createElement: h}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../web/components/onboarding/lib.js'), 'utf8'), ctx);
const lib = ctx.window.TaksOnboarding.lib;
assert.equal(lib.deviceKind({tak_platform:'ATAK-CIV',tak_device:'SAMSUNG SM-F741B'}),'phone');
assert.equal(lib.deviceKind({tak_platform:'WearTAK',tak_device:'Galaxy Watch Ultra'}),'watch');
assert.equal(lib.deviceKind({tak_platform:'ATAK',tak_device:'SM-R960'}),'watch');
assert.equal(lib.deviceKind({tak_platform:'WinTAK'}),'computer');
assert.equal(lib.deviceKind({tak_platform:'Martine'}),'computer');
assert.equal(lib.deviceKind({observed_callsign:'watch',username:'phone'}),'unknown');
const phone={client_uid:'phone-1',tak_platform:'ATAK',observed_callsign:'alexander',state:'current'};
const watch={client_uid:'watch-1',tak_platform:'WearTAK',observed_callsign:'alexander',state:'stale'};
const row={devices:[phone,watch]};
assert.equal(lib.userDeviceCount(row),2);
const strip=lib.DeviceStrip({devices:row.devices});
assert.equal(strip.children[0].length,2);
assert.equal(strip.children[0][0].props.key,'phone-1');
assert.equal(strip.children[0][1].props.key,'watch-1');
assert.match(strip.children[0][1].props.title,/Inaktiv/);
assert.equal(lib.DeviceIcon({device:watch}).props['aria-label'],'Klocka');
assert.equal(lib.DeviceStrip({devices:[]}).children[0].length,0);
console.log('Device classification, shared callsign, presence, accessibility and empty inventory passed');
