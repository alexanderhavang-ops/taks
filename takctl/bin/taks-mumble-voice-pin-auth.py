def utc_now() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


def iso_now() -> str:
    return utc_now().replace(microsecond=0).isoformat().replace("+00:00", "Z")


def log(msg: str) -> None:
    line = f"{iso_now()} {msg}"
    print(line, flush=True)
    with LOG.open("a") as f:
        f.write(line + "\n")


def load_state() -> dict[str, Any]:
    try:
        return json.loads(STATE.read_text())
    except Exception:
        return {"schema": "taks.voice.pin_users.v1", "records": {}}


def save_state(state: dict[str, Any]) -> None:
    tmp = STATE.with_suffix(".tmp")
    state["updated_at"] = iso_now()
    tmp.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n")
    tmp.chmod(0o600)
    tmp.replace(STATE)


def parse_claimed_callsign(name: str) -> str:
    # VX observed format: EAPQ1---uuid
    s = (name or "").strip()
    s = s.split("---", 1)[0]
    s = s.split("/", 1)[0]
    s = s.strip()
    return s.upper()


def x509_summary_from_der(der: bytes) -> dict[str, str]:
    out = {
        "subject": "",
        "issuer": "",
        "serial": "",
        "fingerprint_sha256": "",
        "cn": "",
    }

    with tempfile.TemporaryDirectory() as td:
        der_path = Path(td) / "cert.der"
        der_path.write_bytes(der)

        cmd = [
            "openssl", "x509",
            "-inform", "DER",
            "-in", str(der_path),
            "-noout",
            "-subject",
            "-issuer",
            "-serial",
            "-fingerprint",
            "-sha256",
        ]
        p = subprocess.run(cmd, text=True, capture_output=True)
        raw = (p.stdout or "") + (p.stderr or "")
        for line in raw.splitlines():
            line = line.strip()
            if line.startswith("subject="):
                out["subject"] = line.removeprefix("subject=").strip()
            elif line.startswith("issuer="):
                out["issuer"] = line.removeprefix("issuer=").strip()
            elif line.startswith("serial="):
                out["serial"] = line.removeprefix("serial=").strip()
            elif "Fingerprint=" in line:
                out["fingerprint_sha256"] = line.split("Fingerprint=", 1)[1].strip()

    m = re.search(r"(?:^|[,/ ]+)CN\s*=\s*([^,/|]+)", out["subject"])
    if m:
        out["cn"] = m.group(1).strip()

    return out


def recent_takserver_seen(callsign: str, uid: str) -> tuple[bool, str]:
    # Prototype check: current takserver-messaging.log subscription line.
    # Production should query live TAKServer/session state instead of log text.
    if not TAKSERVER_MESSAGING_LOG.exists():
        return False, "takserver-messaging.log missing"

    # TAK Server logs callsigns with client-provided casing, while VX/Mumble
    # names may be normalized differently. Match callsign case-insensitively,
    # but keep UID exact.
    callsign_re = re.escape(callsign)
    uid_re = re.escape(uid)
    pat = re.compile(
        rf"Set client for subscription: tls:\d+ to {callsign_re} \({uid_re}\) source=([0-9a-fA-F:.]+):(\d+)",
        re.IGNORECASE,
    )

    last = None
    try:
        lines = TAKSERVER_MESSAGING_LOG.read_text(errors="replace").splitlines()
    except Exception as e:
        return False, f"could not read TAKServer log: {e!r}"

    for line in lines[-2000:]:
        m = pat.search(line)
        if m:
            last = line.strip()

    if not last:
        return False, "no recent/current TAKServer subscription log match"

    return True, last



def lookup_takserver_uid_for_callsign(callsign: str) -> str:
    cs = str(callsign or "").strip().upper()
    if not cs:
        return ""

    q = cs.replace("'", "''")
    sql = (
        "SELECT uid "
        "FROM public.client_endpoint "
        "WHERE callsign = '" + q + "' "
        "  AND COALESCE(uid, '') <> '' "
        "ORDER BY "
        "  CASE WHEN COALESCE(username, '') <> '' THEN 0 ELSE 1 END, "
        "  id DESC "
        "LIMIT 1;"
    )

    cmds = [
        ["sudo", "-n", "-u", "postgres", "psql", "-d", "cot", "-AtX", "-v", "ON_ERROR_STOP=1", "-c", sql],
        ["runuser", "-u", "postgres", "--", "psql", "-d", "cot", "-AtX", "-v", "ON_ERROR_STOP=1", "-c", sql],
        ["psql", "-d", "cot", "-AtX", "-v", "ON_ERROR_STOP=1", "-c", sql],
    ]

    for cmd in cmds:
        try:
            r = subprocess.run(cmd, text=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=2)
        except Exception:
            continue

        if r.returncode == 0:
            lines = [x.strip() for x in (r.stdout or "").splitlines() if x.strip()]
            if lines:
                return lines[0]

    return ""


def backfill_record_from_takserver(
    state: dict[str, Any],
    records: dict[str, Any],
    callsign: str,
    got_uid: str,
) -> dict[str, Any]:
    cs = str(callsign or "").strip().upper()
    got = str(got_uid or "").strip()

    if not cs:
        return {}

    rec = records.get(cs) or {}
    expected = str(rec.get("uid") or "").strip()
    if expected:
        return rec

    db_uid = lookup_takserver_uid_for_callsign(cs)
    if not db_uid:
        return rec

    if got and got != db_uid:
        log(f"AUTH_BACKFILL_UID_SKIP callsign={cs!r} db_uid={db_uid!r} got={got!r} reason=cert_uid_mismatch")
        return rec

    rec["callsign"] = cs
    rec["uid"] = db_uid
    rec.setdefault("enabled", True)
    rec.setdefault("allow_empty_vx_password", True)
    rec.setdefault("created_at", iso_now())
    rec["updated_at"] = iso_now()
    rec["last_uid_backfill_from_takserver"] = db_uid

    records[cs] = rec
    state["records"] = records
    save_state(state)

    log(f"AUTH_BACKFILL_UID callsign={cs!r} uid={db_uid!r} source=client_endpoint")
    return rec


def user_id_for(callsign: str, uid: str, identity: str = "") -> int:
    # Murmur wants a non-negative stable int for externally-authenticated users.
    # VX may open multiple simultaneous Mumble sessions for the same TAK callsign/UID.
    # If we collapse all of them to the same Murmur user id, Murmur disconnects
    # the previous one as a "ghost". Include the VX-provided unique name suffix.
    h = hashlib.sha256(f"{callsign}|{uid}|{identity}".encode()).digest()
    return 100000 + int.from_bytes(h[:4], "big") % 2000000000


def record_failure(state: dict[str, Any], key: str, reason: str) -> None:
    rec = state.setdefault("records", {}).setdefault(key, {})
    failures = list(rec.get("failed_attempts") or [])
    failures.append({"ts": iso_now(), "reason": reason})
    rec["failed_attempts"] = failures[-20:]
    rec["last_failure_at"] = iso_now()
    rec["last_failure_reason"] = reason
    save_state(state)


def too_many_recent_failures(rec: dict[str, Any]) -> bool:
    return False

def load_service_passwords() -> set[str]:
    passwords: set[str] = set()

    for path in (
        SERVICE_PASSWORD_FILE,
        Path("/etc/taks-bootstrap.d/secrets.d/murmur.conf"),
    ):
        try:
            text = path.read_text().strip()
        except Exception:
            continue

        if not text:
            continue

        # Simple file format: entire file is the password.
        if "\n" not in text and "=" not in text:
            passwords.add(text.strip().strip('"').strip("'"))

        # Shell-ish config format: find values containing mumble/pass/password.
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            lk = k.lower()
            if "mumble" in lk or "pass" in lk or "password" in lk:
                v = v.strip().strip('"').strip("'")
                if v:
                    passwords.add(v)

    # Known current lab default, kept as fallback for this runtime prototype.
    passwords.add("mumble-pass-46hvbat-pass")
    return {p for p in passwords if p}


def service_user_id_for(name: str) -> int:
    label = name or "taks-local-service"
    h = hashlib.sha256(f"local-service|{label}".encode()).digest()
    return 2100000000 + int.from_bytes(h[:3], "big") % 40000000


class VoicePinAuthenticator(MumbleServer.ServerAuthenticator):
    def authenticate(self, name, pw, certificates, certhash, certstrong, current=None):
        callsign = parse_claimed_callsign(name)
        state = load_state()
        records = state.get("records") or {}
        rec = records.get(callsign) or {}

        try:
            certs = list(certificates or [])
            pw = pw or ""
            cert_info = {}
            cert_cn = ""
            cert_sha256 = ""

            if certs:
                der = bytes(certs[0])
                cert_sha256 = hashlib.sha256(der).hexdigest()
                cert_info = x509_summary_from_der(der)
                cert_cn = cert_info.get("cn") or ""

            log(
                "AUTH_ATTEMPT "
                f"name={name!r} callsign={callsign!r} "
                f"pw_len={len(pw)} cert_count={len(certs)} "
                f"cert_cn={cert_cn!r} certhash={certhash!r} certstrong={certstrong!r}"
            )

            # Non-VX local/service clients such as Martine, takctl health checks,
            # and dump tools do not present the ATAK/VX self-signed cert. Let them
            # in only when they know the service Mumble password. We cannot rely on
            # 127.0.0.1 here because Murmur's ServerAuthenticator callback does not
            # pass the original Mumble client source IP.
            if not certs:
                if str(pw) in load_service_passwords():
                    svc_name = str(name or "taks-local-service")
                    svc_id = service_user_id_for(svc_name)
                    log(f"AUTH_ACCEPT_SERVICE name={svc_name!r} user_id={svc_id}")
                    return (svc_id, svc_name, [])
                log(f"AUTH_REJECT_SERVICE name={name!r} reason=missing_or_bad_service_password")
                return (-1, "", [])

            def reject(reason: str):
                log(f"AUTH_REJECT callsign={callsign!r} uid={cert_cn!r} reason={reason}")
                record_failure(state, callsign or "UNKNOWN", reason)
                return (-1, "", [])

            if not callsign:
                return reject("missing_callsign")

            if not rec:
                rec = backfill_record_from_takserver(state, records, callsign, cert_cn)
                if not rec:
                    return reject("unknown_callsign")

            if False and too_many_recent_failures(rec):
                return reject("rate_limited")

            if not rec.get("enabled", True):
                return reject("voice_disabled")

            expected_uid = str(rec.get("uid") or "").strip()
            if not expected_uid:
                rec = backfill_record_from_takserver(state, records, callsign, cert_cn)
                expected_uid = str(rec.get("uid") or "").strip()

            expected_pin = str(rec.get("voice_pin") or "").strip()

            if not cert_cn:
                return reject("missing_vx_cert_cn")

            if cert_cn != expected_uid:
                return reject(f"uid_mismatch expected={expected_uid!r} got={cert_cn!r}")

            # VX does not reliably send user-entered passwords/PINs.
            # In passwordless UID-presence mode, accept empty pw after UID/callsign
            # validation and TAKServer presence validation below.
            pass

            seen_ok, seen_detail = recent_takserver_seen(callsign, expected_uid)
            if not seen_ok:
                return reject("no_takserver_uid_callsign_presence: " + seen_detail)

            user_id = user_id_for(callsign, expected_uid, name)

            rec.setdefault("mumble_identities", {})
            rec["mumble_identities"][str(user_id)] = {
                "name": name,
                "callsign": callsign,
                "uid": expected_uid,
                "last_seen_at": iso_now(),
            }
            rec["last_success_at"] = iso_now()
            rec["last_vx_cert_cn"] = cert_cn
            rec["last_vx_cert_sha256_der"] = cert_sha256
            rec["last_murmur_certhash"] = certhash
            rec["last_certstrong"] = bool(certstrong)
            rec["last_takserver_presence"] = seen_detail
            rec["failed_attempts"] = []
            records[callsign] = rec
            state["records"] = records
            save_state(state)

            log(
                "AUTH_ACCEPT "
                f"callsign={callsign!r} uid={expected_uid!r} "
                f"user_id={user_id} vx_cert_sha256={cert_sha256}"
            )

            # Groups are empty for this first slice. Channel ACL/groups come next.
            # Return the VX-provided unique Mumble name, not just the TAK callsign.
            # Otherwise multiple VX sessions for the same callsign fight each other.
            return (user_id, name, [])

        except Exception:
            log("AUTH_EXCEPTION " + traceback.format_exc().replace("\n", " | "))
            return (-1, "", [])

    def getInfo(self, id, current=None):
        return (False, {})

    def nameToId(self, name, current=None):
        callsign = parse_claimed_callsign(name)
        state = load_state()
        rec = (state.get("records") or {}).get(callsign) or {}
        uid = str(rec.get("uid") or "")
        if callsign and uid:
            return user_id_for(callsign, uid, name)
        return -2

    def idToName(self, id, current=None):
        state = load_state()
        for callsign, rec in (state.get("records") or {}).items():
            uid = str(rec.get("uid") or "")
            identities = rec.get("mumble_identities") or {}
            if str(id) in identities:
                return str(identities[str(id)].get("name") or rec.get("callsign") or callsign)
            if uid and user_id_for(callsign, uid, str(rec.get("last_mumble_name") or "")) == id:
                return str(rec.get("callsign") or callsign)
        return ""

    def idToTexture(self, id, current=None):
        return b""


def install_authenticator() -> None:
    secret = SECRET_FILE.read_text().strip()

    init_data = Ice.InitializationData()
    init_data.properties = Ice.createProperties()
    init_data.properties.setProperty("Ice.ImplicitContext", "Shared")

    communicator = Ice.initialize(sys.argv, init_data)
    communicator.getImplicitContext().setContext({"secret": secret})

    adapter = communicator.createObjectAdapterWithEndpoints(
        "TaksMumbleVoicePinAuth",
        "tcp -h 127.0.0.1"
    )

    servant = VoicePinAuthenticator()
    auth_proxy = MumbleServer.ServerAuthenticatorPrx.uncheckedCast(
        adapter.addWithUUID(servant)
    )

    meta_base = communicator.stringToProxy("Meta:tcp -h 127.0.0.1 -p 6502")
    meta = MumbleServer.MetaPrx.checkedCast(meta_base)
    if not meta:
        raise RuntimeError("Could not cast Meta proxy")

    servers = []
    for method in ("getBootedServers", "getAllServers"):
        try:
            servers = list(getattr(meta, method)())
            if servers:
                log(f"using meta.{method}(), servers={len(servers)}")
                break
        except Exception as e:
            log(f"meta.{method} failed: {e!r}")

    if not servers:
        raise RuntimeError("No Murmur virtual servers found via ICE")

    adapter.activate()

    for server in servers:
        sid = server.id()
        server.setAuthenticator(auth_proxy)
        log(f"setAuthenticator installed on server_id={sid}")

    log("READY voice PIN authenticator active")
    communicator.waitForShutdown()


def main() -> int:
    LOG.parent.mkdir(parents=True, exist_ok=True)
    install_authenticator()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
