def lang_norm(lang: str | None) -> str:
    l = (lang or "").strip().lower()
    if l.startswith("en"):
        return "en"
    return "sv"


def t(lang: str | None, key: str, **fmt) -> str:
    l = lang_norm(lang)
    s = (_I18N.get(l) or {}).get(key)
    if s is None:
        s = (_I18N.get("en") or {}).get(key, key)
    try:
        return s.format(**fmt)
    except Exception:
        return s
