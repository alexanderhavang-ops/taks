#!/usr/bin/env bash
set -euo pipefail

log() {
  printf '[tak-certs-config] %s\n' "$*"
}

read_kv() {
  local file="$1"
  local key="$2"
  [ -f "$file" ] || return 1
  sed -n "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*//p" "$file" | head -n 1
}

main() {
  local conf="/opt/tak/tools/takctl/conf.d/certs.conf"
  local sec="/opt/tak/tools/takctl/secrets.d/certs.conf"
  local dst="/opt/tak/certs/cert-metadata.sh"

  if [ ! -f "$conf" ]; then
    log "missing $conf; skipping"
    return 0
  fi

  mkdir -p /opt/tak/certs

  local COUNTRY STATE CITY ORGANIZATION ORGANIZATIONAL_UNIT CAPASS PASS
  COUNTRY="$(read_kv "$conf" cert_country || true)"
  STATE="$(read_kv "$conf" cert_state || true)"
  CITY="$(read_kv "$conf" cert_city || true)"
  ORGANIZATION="$(read_kv "$conf" cert_organization || true)"
  ORGANIZATIONAL_UNIT="$(read_kv "$conf" cert_organizational_unit || true)"
  CAPASS="$(read_kv "$sec" cert_capass || true)"
  PASS="$(read_kv "$sec" cert_pass || true)"

  cat > "$dst" <<EOT
# Generated by TAKS bundle install from takctl runtime config
COUNTRY=${COUNTRY:-SE}
STATE=${STATE}
CITY=${CITY}
ORGANIZATION=${ORGANIZATION:-TAK}
ORGANIZATIONAL_UNIT=${ORGANIZATIONAL_UNIT}
CAPASS=${CAPASS:-atakatak}
PASS=${PASS:-$CAPASS}
DIR=files

if [[ -z \${STATE} || -z \${CITY} || -z \${ORGANIZATIONAL_UNIT} ]]; then
  echo "Please set the following variables before running this script: STATE, CITY, ORGANIZATIONAL_UNIT."
  exit -1
fi

SUBJBASE="/C=\${COUNTRY}/"
if [ -n "\$STATE" ]; then
 SUBJBASE+="ST=\${STATE}/"
fi
if [ -n "\$CITY" ]; then
 SUBJBASE+="L=\${CITY}/"
fi
if [ -n "\$ORGANIZATION" ]; then
 SUBJBASE+="O=\${ORGANIZATION}/"
fi
if [ -n "\$ORGANIZATIONAL_UNIT" ]; then
 SUBJBASE+="OU=\${ORGANIZATIONAL_UNIT}/"
fi
EOT

  chmod 600 "$dst"
  log "wrote $dst from runtime config"
}

main "$@"
